use super::*;
use crate::domains::changes::changed_files::changed_files;
use crate::domains::repository::names::object_id::ObjectId;
use crate::domains::repository::test_repo::TestRepo;

async fn flagged(fixture: &TestRepo, old: &TreeSource, new: &TreeSource) -> Vec<(String, bool)> {
    let repo = GitRepo::open(fixture.path()).await.unwrap();
    let mut files = changed_files(&repo, old, new).await.unwrap();
    GeneratedDetector::default()
        .flag(&repo, &mut files, new)
        .await;
    files
        .iter()
        .map(|file| (file.path.to_string(), file.generated))
        .collect()
}

fn fixture_with_generated_files() -> (TestRepo, TreeSource) {
    let fixture = TestRepo::init();
    let base = fixture.commit("seed.txt", "s\n");
    std::fs::write(
        fixture.path().join("api.rs"),
        "// @generated by codegen\nfn x() {}\n",
    )
    .unwrap();
    std::fs::write(fixture.path().join("hand.rs"), "// written by a person\n").unwrap();
    std::fs::write(fixture.path().join("Cargo.lock"), "# lock\n").unwrap();
    std::fs::write(fixture.path().join("opt-out.lock"), "# lock\n").unwrap();
    std::fs::write(fixture.path().join("marked.txt"), "plain\n").unwrap();
    std::fs::write(
        fixture.path().join(".gitattributes"),
        "marked.txt linguist-generated\nopt-out.lock -linguist-generated\n",
    )
    .unwrap();
    (fixture, TreeSource::Object(base))
}

fn expected() -> Vec<(String, bool)> {
    [
        (".gitattributes", false),
        ("Cargo.lock", true),
        ("api.rs", true),
        ("hand.rs", false),
        ("marked.txt", true),
        ("opt-out.lock", false),
    ]
    .map(|(path, generated)| (path.to_owned(), generated))
    .to_vec()
}

#[tokio::test]
async fn flags_by_attribute_then_path_then_content_in_the_worktree() {
    let (fixture, base) = fixture_with_generated_files();
    assert_eq!(
        flagged(&fixture, &base, &TreeSource::Worktree).await,
        expected()
    );
}

#[tokio::test]
async fn flags_the_same_files_when_the_new_side_is_a_commit() {
    let (fixture, base) = fixture_with_generated_files();
    fixture.git(&["add", "--all"]);
    fixture.git(&["commit", "--quiet", "--message", "gen"]);
    let tip = ObjectId::parse(&fixture.git(&["rev-parse", "HEAD"])).unwrap();
    assert_eq!(
        flagged(&fixture, &base, &TreeSource::Object(tip)).await,
        expected()
    );
}

#[tokio::test]
async fn a_repeated_blob_is_not_read_again() {
    let fixture = TestRepo::init();
    let base = TreeSource::Object(fixture.commit("seed.txt", "s\n"));
    std::fs::write(fixture.path().join("api.rs"), "// @generated\n").unwrap();
    fixture.git(&["add", "--all"]);
    fixture.git(&["commit", "--quiet", "--message", "gen"]);
    let tip = TreeSource::Object(ObjectId::parse(&fixture.git(&["rev-parse", "HEAD"])).unwrap());
    let repo = GitRepo::open(fixture.path()).await.unwrap();
    let detector = GeneratedDetector::default();
    let old = base;
    let mut first = changed_files(&repo, &old, &tip).await.unwrap();
    detector.flag(&repo, &mut first, &tip).await;
    assert!(first.iter().any(|file| file.generated));
    let reads = repo.objects_spawned();
    let mut again = changed_files(&repo, &old, &tip).await.unwrap();
    detector.flag(&repo, &mut again, &tip).await;
    assert_eq!(first, again);
    assert_eq!(repo.objects_spawned(), reads);
}
