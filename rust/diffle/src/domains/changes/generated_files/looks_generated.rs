//! Whether a file looks machine-written: by where it lives and what it is called, or by a
//! generator's marker near the top of its text.

/// How much of a file the content sniff reads. Markers past this are missed; a
/// `linguist-generated` attribute is the escape hatch.
pub const SNIFF_BYTES: usize = 4096;

const LOCKFILES: [&str; 10] = [
    "package-lock.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "uv.lock",
    "Cargo.lock",
    "poetry.lock",
    "composer.lock",
    "Gemfile.lock",
    "go.sum",
    "flake.lock",
];
const GENERATED_SUFFIXES: [&str; 17] = [
    ".lock",
    ".min.js",
    ".min.css",
    ".min.mjs",
    ".js.map",
    ".mjs.map",
    ".cjs.map",
    ".css.map",
    ".snap",
    "_pb2.py",
    "_pb2.pyi",
    "_pb2_grpc.py",
    "_pb2_grpc.pyi",
    ".g.dart",
    ".freezed.dart",
    ".gr.dart",
    ".pb.go",
];
const PROTOBUF_EXTENSIONS: [&str; 5] = ["cc", "h", "swift", "rb", "dart"];
const GENERATED_INFIX: &str = ".generated.";
const SNAPSHOT_DIR: &str = "__snapshots__";
const GENERATED_DIRS: [&str; 3] = ["generated", "__generated__", "_generated"];
const BUNDLE_DIRS: [&str; 2] = ["dist", "build"];
const BUNDLE_EXTENSIONS: [&str; 2] = [".js", ".css"];

/// Marker phrases the common generators put in a file header; `true` where case is ignored.
const MARKERS: [(&str, bool); 4] = [
    ("@generated", false),
    ("DO NOT EDIT", false),
    ("Code generated by", false),
    ("automatically generated", true),
];
/// Spellings of "autogenerated" that are matched exactly (`[Aa]uto-?generated`).
const AUTOGENERATED: [&str; 4] = [
    "autogenerated",
    "Autogenerated",
    "auto-generated",
    "Auto-generated",
];
/// Generators write the marker in a comment; prose or code that mentions one does not count.
const COMMENT_STARTS: [&str; 10] = [
    "#", "//", "/*", "*", "--", "<!--", ";", "%", "\"\"\"", "'''",
];
/// Ruby's block comment, whatever the case and whatever follows.
const BLOCK_COMMENT_START: &str = "=begin";
/// Batch-file remarks, which only count as a whole word.
const REMARK_STARTS: [&str; 2] = ["rem", "@rem"];

/// True when `path` matches a generated-file convention, or the first bytes carry a
/// generator marker. `head` is `None` when nothing could be read; binary content never counts.
#[must_use]
pub fn looks_generated(path: &str, head: Option<&[u8]>) -> bool {
    path_looks_generated(path) || head.is_some_and(head_looks_generated)
}

#[must_use]
pub fn path_looks_generated(path: &str) -> bool {
    let (dirs, name) = path.rsplit_once('/').unwrap_or(("", path));
    let mut components = dirs.split('/').filter(|component| !component.is_empty());
    let in_dir = |wanted: &[&str]| components.clone().any(|dir| wanted.contains(&dir));
    LOCKFILES.contains(&name)
        || GENERATED_SUFFIXES
            .iter()
            .any(|suffix| name.ends_with(suffix))
        || is_protobuf_output(name)
        || has_generated_infix(name)
        || in_dir(&[SNAPSHOT_DIR])
        || in_dir(&GENERATED_DIRS)
        || components
            .next_back()
            .is_some_and(|parent| is_bundle(parent, name))
}

/// `name.pb.<ext>` for the languages protoc writes.
fn is_protobuf_output(name: &str) -> bool {
    name.rsplit_once(".pb.")
        .is_some_and(|(stem, ext)| !stem.is_empty() && PROTOBUF_EXTENSIONS.contains(&ext))
}

/// `.generated.` with something after it, as in `schema.generated.ts`.
fn has_generated_infix(name: &str) -> bool {
    name.find(GENERATED_INFIX)
        .is_some_and(|at| at + GENERATED_INFIX.len() < name.len())
}

fn is_bundle(parent: &str, name: &str) -> bool {
    BUNDLE_DIRS.contains(&parent)
        && BUNDLE_EXTENSIONS
            .iter()
            .any(|extension| name.len() > extension.len() && name.ends_with(extension))
}

fn head_looks_generated(head: &[u8]) -> bool {
    let sniffed = head.get(..SNIFF_BYTES).unwrap_or(head);
    if sniffed.contains(&0) {
        return false;
    }
    String::from_utf8_lossy(sniffed)
        .split('\n')
        .any(|line| is_comment(line) && has_marker(line))
}

fn is_comment(line: &str) -> bool {
    let line = line.trim_start();
    let lower = line.to_ascii_lowercase();
    COMMENT_STARTS.iter().any(|start| line.starts_with(start))
        || lower.starts_with(BLOCK_COMMENT_START)
        || REMARK_STARTS
            .iter()
            .any(|start| lower.starts_with(start) && ends_word(&lower, start.len()))
}

fn has_marker(line: &str) -> bool {
    let lower = line.to_ascii_lowercase();
    MARKERS.iter().any(|&(phrase, case_blind)| {
        let (haystack, needle) = match case_blind {
            true => (lower.as_str(), phrase.to_ascii_lowercase()),
            false => (line, phrase.to_owned()),
        };
        // `@generated` has no word character before it to border; the others do.
        let leading = needle.starts_with(|c: char| is_word(c));
        occurrences(haystack, &needle).any(|at| {
            (!leading || starts_word(haystack, at)) && ends_word(haystack, at + needle.len())
        })
    }) || AUTOGENERATED.iter().any(|phrase| {
        occurrences(line, phrase)
            .any(|at| starts_word(line, at) && ends_word(line, at + phrase.len()))
    })
}

fn occurrences<'a>(haystack: &'a str, needle: &'a str) -> impl Iterator<Item = usize> + 'a {
    haystack.match_indices(needle).map(|(at, _)| at)
}

const fn is_word(c: char) -> bool {
    c.is_ascii_alphanumeric() || c == '_'
}

/// No word character just before `at`.
fn starts_word(text: &str, at: usize) -> bool {
    !text
        .get(..at)
        .and_then(|before| before.chars().next_back())
        .is_some_and(is_word)
}

/// No word character at `at`.
fn ends_word(text: &str, at: usize) -> bool {
    !text
        .get(at..)
        .and_then(|after| after.chars().next())
        .is_some_and(is_word)
}

