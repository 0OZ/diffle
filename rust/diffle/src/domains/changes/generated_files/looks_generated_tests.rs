use super::*;

fn head(text: &str) -> Option<&[u8]> {
    Some(text.as_bytes())
}

#[test]
fn conventional_paths_are_generated() {
    for path in [
        "package-lock.json",
        "web/pnpm-lock.yaml",
        "Cargo.lock",
        "deps.lock",
        "app.min.js",
        "static/site.min.css",
        "bundle.js.map",
        "web/__snapshots__/a.test.ts.snap",
        "x.snap",
        "api_pb2.py",
        "api_pb2_grpc.pyi",
        "api.pb.go",
        "api.pb.swift",
        "model.g.dart",
        "model.freezed.dart",
        "schema.generated.ts",
        "src/generated/types.ts",
        "src/__generated__/a.ts",
        "dist/main.js",
        "pkg/build/theme.css",
    ] {
        assert!(path_looks_generated(path), "{path}");
    }
}

#[test]
fn ordinary_paths_are_not() {
    for path in [
        "src/main.rs",
        "lockfile.rs",
        "locks/readme.md",
        "dist/readme.md",
        "dist/nested/app.js",
        "dist/.js",
        "generated.rs",
        "my.generated.",
        "src/generatedfoo/a.ts",
        "api.pb.zip",
        "build.js",
    ] {
        assert!(!path_looks_generated(path), "{path}");
    }
}

#[test]
fn a_marker_in_a_leading_comment_marks_the_file() {
    for text in [
        "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
        "# @generated by the tool\nx = 1\n",
        "/* automatically generated */\n",
        "-- Auto-generated by migrations\n",
        "<!-- Autogenerated file -->\n",
        "<?php\n// @generated\n",
        "   * DO NOT EDIT this file\n",
        "REM Autogenerated\n",
        "=begin @generated\n",
        "\"\"\" auto-generated \"\"\"\n",
    ] {
        assert!(looks_generated("src/a.txt", head(text)), "{text}");
    }
}

#[test]
fn prose_and_code_that_only_mention_a_marker_do_not_count() {
    for text in [
        "let note = \"DO NOT EDIT\";\n",
        "This file is autogenerated, said the manual.\n",
        "// notgenerated and auto-generatedly\n",
        "// DO NOT EDITING\n",
        "// regenerated @generatedness\n",
        "remember to rest\n",
    ] {
        assert!(!looks_generated("src/a.txt", head(text)), "{text}");
    }
}

#[test]
fn binary_and_unread_content_never_counts_and_the_sniff_stops_at_its_limit() {
    assert!(!looks_generated("a.bin", head("// @generated\0")));
    assert!(!looks_generated("a.txt", None));
    assert!(!looks_generated("a.txt", head("")));
    let late = format!("{}\n// @generated\n", "x".repeat(SNIFF_BYTES));
    assert!(!looks_generated("a.txt", head(&late)));
    assert!(looks_generated("package-lock.json", None));
}
